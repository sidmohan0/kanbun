import type { Row, WorkflowStateType } from "@kanbun/model";
import { MutationError, defineMutator, type DecideContext, type MutatorContext } from "@kanbun/sync";
import { z } from "zod";
import { firstKey, keyAfter } from "./ordering";
import { color, id, nullable } from "./schema";

const stateType = z.enum(["triage", "backlog", "unstarted", "started", "completed", "canceled"]);

export const DEFAULT_STATES: {
  key: "triage" | "backlog" | "todo" | "inProgress" | "done" | "canceled";
  name: string;
  type: WorkflowStateType;
  color: string;
}[] = [
  { key: "triage", name: "Triage", type: "triage", color: "#95A2B3" },
  { key: "backlog", name: "Backlog", type: "backlog", color: "#95A2B3" },
  { key: "todo", name: "Todo", type: "unstarted", color: "#E2E2E2" },
  { key: "inProgress", name: "In Progress", type: "started", color: "#F2C94C" },
  { key: "done", name: "Done", type: "completed", color: "#5E6AD2" },
  { key: "canceled", name: "Canceled", type: "canceled", color: "#95A2B3" },
];

/** Team admin = workspace admin/owner, or a team owner. Agents never administer teams. */
export function requireTeamAdmin(ctx: MutatorContext, teamId: string): void {
  if (ctx.actor.type !== "user") throw new MutationError("team admin required", "forbidden");
  requireTeamAccess(ctx, teamId);
  const me = ctx.store.get("user", ctx.actorId);
  if (me?.role === "admin" || me?.role === "owner") return;
  const m = ctx.store.list("teamMembership", { teamId, userId: ctx.actorId })[0];
  if (!m?.owner || m.archivedAt) throw new MutationError("team admin required", "forbidden");
}

export function requireTeamAccess(ctx: DecideContext, teamId: string): Row<"team"> {
  const team = ctx.store.get("team", teamId);
  if (!team || team.archivedAt) throw new MutationError("team not found", "not_found");
  if (team.visibility === "private") {
    const userId =
      ctx.actor.type === "agent" ? (ctx.store.get("agent", ctx.actorId)?.ownerId ?? ctx.actorId) : ctx.actorId;
    const m = ctx.store.list("teamMembership", { teamId, userId })[0];
    if (!m || m.archivedAt) throw new MutationError("not a member of this private team", "forbidden");
  }
  if (ctx.actor.type === "agent") {
    const scoped = ctx.store.get("agent", ctx.actorId)?.scopes.teamIds ?? [];
    if (scoped.length && !scoped.includes(teamId))
      throw new MutationError("agent is not scoped to this team", "forbidden");
  }
  return team;
}

const teamPatch = z
  .object({
    name: z.string().trim().min(1).max(80),
    displayName: z.string().trim().min(1).max(80),
    description: nullable(z.string()),
    icon: nullable(z.string()),
    color: nullable(color),
    timezone: z.string(),
    visibility: z.enum(["public", "private"]),
    parentId: nullable(id),
    cyclesEnabled: z.boolean(),
    cycleDuration: z.number().int().min(1).max(8),
    cycleCooldownTime: z.number().int().min(0).max(4),
    cycleStartDay: z.number().int().min(0).max(6),
    cycleLockToActive: z.boolean(),
    upcomingCycleCount: z.number().int().min(0).max(6),
    triageEnabled: z.boolean(),
    requirePriorityToLeaveTriage: z.boolean(),
    issueEstimationType: z.enum(["notUsed", "exponential", "fibonacci", "linear", "tShirt"]),
    issueEstimationAllowZero: z.boolean(),
    issueEstimationExtended: z.boolean(),
    defaultIssueEstimate: z.number().min(0),
    autoArchivePeriod: z.number().int().min(0),
    autoClosePeriod: nullable(z.number().int().min(0)),
    autoCloseStateId: nullable(id),
    defaultIssueStateId: nullable(id),
    triageIssueStateId: nullable(id),
    setIssueSortOrderOnStateChange: z.enum(["top", "bottom", "noChange"]),
  })
  .partial();

export const mutators = {
  teamCreate: defineMutator({
    args: z.object({
      id,
      name: z.string().trim().min(1).max(80),
      key: z.string().regex(/^[A-Za-z][A-Za-z0-9]{0,6}$/, "1–7 letters or digits, starting with a letter"),
      icon: nullable(z.string()).optional(),
      color: nullable(color).optional(),
      visibility: z.enum(["public", "private"]).optional(),
      timezone: z.string().optional(),
      /** ids for the default workflow states, generated by the caller. */
      stateIds: z.object({ backlog: id, todo: id, inProgress: id, done: id, canceled: id, triage: id.optional() }),
      membershipId: id,
    }),
    description: "Create a team with its default workflow states; the caller becomes its first owner.",
    run(ctx, args) {
      const creator = ctx.store.get("user", ctx.actorId);
      if (
        ctx.actor.type !== "user" ||
        !creator?.active ||
        creator.archivedAt ||
        !["owner", "admin"].includes(creator.role)
      )
        throw new MutationError("workspace owner or admin required to create a team", "forbidden");
      const key = args.key.toUpperCase();
      if (ctx.store.list("team", { key }).length) throw new MutationError(`team key ${key} is taken`, "conflict");
      ctx.store.insert("team", {
        id: args.id,
        name: args.name,
        displayName: args.name,
        key,
        icon: args.icon ?? null,
        color: args.color ?? null,
        visibility: args.visibility ?? "public",
        timezone: args.timezone ?? "Etc/UTC",
        defaultIssueStateId: args.stateIds.backlog,
        triageIssueStateId: args.stateIds.triage ?? null,
        createdAt: ctx.now,
        updatedAt: ctx.now,
      } as Row<"team">);
      let position = 0;
      for (const s of DEFAULT_STATES) {
        const stateId = args.stateIds[s.key];
        if (!stateId) continue;
        ctx.store.insert("workflowState", {
          id: stateId,
          teamId: args.id,
          name: s.name,
          type: s.type,
          color: s.color,
          position: position++,
          createdAt: ctx.now,
          updatedAt: ctx.now,
        } as Row<"workflowState">);
      }
      ctx.store.insert("teamMembership", {
        id: args.membershipId,
        teamId: args.id,
        userId: ctx.actorId,
        owner: true,
        sortOrder: firstKey(),
        createdAt: ctx.now,
        updatedAt: ctx.now,
      } as Row<"teamMembership">);
    },
  }),

  teamUpdate: defineMutator({
    args: z.object({ id, patch: teamPatch }),
    description: "Change team settings (name, key display, cycles, triage, estimation, auto-archive).",
    run(ctx, args) {
      requireTeamAdmin(ctx, args.id);
      if (args.patch.parentId === args.id) throw new MutationError("a team cannot be its own parent", "invalid");
      for (const field of ["defaultIssueStateId", "triageIssueStateId", "autoCloseStateId"] as const) {
        const stateId = args.patch[field];
        if (!stateId) continue;
        const state = ctx.store.get("workflowState", stateId);
        if (!state || state.teamId !== args.id || state.archivedAt)
          throw new MutationError("team state must be active and belong to this team", "invalid");
      }
      ctx.store.patch("team", args.id, { ...args.patch, updatedAt: ctx.now });
    },
  }),

  teamRetire: defineMutator({
    args: z.object({ id }),
    description: "Retire a team: hidden from navigation, issues kept read-only.",
    run(ctx, args) {
      requireTeamAdmin(ctx, args.id);
      ctx.store.patch("team", args.id, { retiredAt: ctx.now, updatedAt: ctx.now });
    },
  }),

  teamDelete: defineMutator({
    args: z.object({ id }),
    description: "Archive a team and everything in it.",
    run(ctx, args) {
      requireTeamAdmin(ctx, args.id);
      ctx.store.patch("team", args.id, { archivedAt: ctx.now, updatedAt: ctx.now });
    },
  }),

  teamMembershipCreate: defineMutator({
    args: z.object({ id, teamId: id, userId: id.or(z.string().min(1)), owner: z.boolean().optional() }),
    description: "Add a member to a team. Private teams, and granting ownership, require a team admin.",
    run(ctx, args) {
      const team = ctx.store.get("team", args.teamId);
      if (!team || team.archivedAt) throw new MutationError("team not found", "not_found");
      if (team.visibility === "private" || args.owner) requireTeamAdmin(ctx, args.teamId);
      if (!ctx.store.get("user", args.userId)) throw new MutationError("user not found", "not_found");
      if (ctx.store.list("teamMembership", { teamId: args.teamId, userId: args.userId }).length) return;
      const existing = ctx.store.list("teamMembership", { teamId: args.teamId }).map((m) => m.sortOrder);
      ctx.store.insert("teamMembership", {
        id: args.id,
        teamId: args.teamId,
        userId: args.userId,
        owner: args.owner ?? false,
        sortOrder: keyAfter(existing),
        createdAt: ctx.now,
        updatedAt: ctx.now,
      } as Row<"teamMembership">);
    },
  }),

  teamMembershipDelete: defineMutator({
    args: z.object({ teamId: id, userId: z.string().min(1) }),
    description: "Remove a member from a team (self, or by a team admin).",
    run(ctx, args) {
      if (args.userId !== ctx.actorId) requireTeamAdmin(ctx, args.teamId);
      for (const m of ctx.store.list("teamMembership", { teamId: args.teamId, userId: args.userId }))
        ctx.store.delete("teamMembership", m.id);
    },
  }),

  workflowStateCreate: defineMutator({
    args: z.object({
      id,
      teamId: id,
      name: z.string().trim().min(1).max(40),
      type: stateType,
      color,
      description: nullable(z.string()).optional(),
    }),
    description: "Add a workflow state to a team.",
    run(ctx, args) {
      requireTeamAdmin(ctx, args.teamId);
      const siblings = ctx.store.list("workflowState", { teamId: args.teamId, type: args.type });
      const position = Math.max(-1, ...siblings.map((s) => s.position)) + 1;
      ctx.store.insert("workflowState", {
        id: args.id,
        teamId: args.teamId,
        name: args.name,
        type: args.type,
        color: args.color,
        description: args.description ?? null,
        position,
        createdAt: ctx.now,
        updatedAt: ctx.now,
      } as Row<"workflowState">);
    },
  }),

  workflowStateUpdate: defineMutator({
    args: z.object({
      id,
      patch: z
        .object({
          name: z.string().trim().min(1).max(40),
          color,
          description: nullable(z.string()),
          position: z.number(),
        })
        .partial(),
    }),
    description: "Rename, recolour or reorder a workflow state.",
    run(ctx, args) {
      const s = ctx.store.get("workflowState", args.id);
      if (!s || s.archivedAt) throw new MutationError("state not found", "not_found");
      requireTeamAdmin(ctx, s.teamId);
      ctx.store.patch("workflowState", args.id, { ...args.patch, updatedAt: ctx.now });
    },
  }),

  workflowStateReorder: defineMutator({
    args: z.object({ teamId: id, type: stateType, stateIds: z.array(id) }),
    description: "Reorder the active states in one team's workflow category atomically.",
    run(ctx, args) {
      requireTeamAdmin(ctx, args.teamId);
      const current = ctx.store
        .list("workflowState", { teamId: args.teamId, type: args.type })
        .filter((state) => !state.archivedAt);
      const requested = new Set(args.stateIds);
      if (
        requested.size !== args.stateIds.length ||
        requested.size !== current.length ||
        current.some((state) => !requested.has(state.id))
      )
        throw new MutationError("workflow changed; refresh and reorder its current states", "conflict");
      args.stateIds.forEach((stateId, position) =>
        ctx.store.patch("workflowState", stateId, { position, updatedAt: ctx.now }),
      );
    },
  }),

  workflowStateDelete: defineMutator({
    args: z.object({ id, moveIssuesToStateId: id }),
    description: "Archive a workflow state, moving its issues to another state in the same team.",
    run(ctx, args) {
      const s = ctx.store.get("workflowState", args.id);
      if (!s || s.archivedAt) throw new MutationError("state not found", "not_found");
      requireTeamAdmin(ctx, s.teamId);
      const target = ctx.store.get("workflowState", args.moveIssuesToStateId);
      if (!target || target.teamId !== s.teamId || target.archivedAt || target.id === s.id)
        throw new MutationError("target state must be a different active state in the same team", "invalid");
      for (const issue of ctx.store.list("issue", { teamId: s.teamId })) {
        if (issue.stateId !== s.id && issue.assertedStateId !== s.id && issue.derivedStateId !== s.id) continue;
        const assertedStateId = issue.assertedStateId === s.id ? target.id : issue.assertedStateId;
        const derivedStateId =
          issue.derivedStateId === s.id
            ? target.id
            : (issue.derivedStateId ?? (issue.stateId === s.id ? target.id : issue.stateId));
        const stateId = assertedStateId ?? derivedStateId;
        const effective = ctx.store.get("workflowState", stateId)!;
        const changed = stateId !== issue.stateId;
        ctx.store.patch("issue", issue.id, {
          assertedStateId,
          derivedStateId,
          stateId,
          updatedAt: ctx.now,
          startedAt: changed && effective.type === "started" ? (issue.startedAt ?? ctx.now) : issue.startedAt,
          completedAt: !changed ? issue.completedAt : effective.type === "completed" ? ctx.now : null,
          canceledAt: !changed ? issue.canceledAt : effective.type === "canceled" ? ctx.now : null,
        });
      }
      const team = ctx.store.get("team", s.teamId)!;
      const references: Partial<Row<"team">> = {};
      for (const field of ["defaultIssueStateId", "triageIssueStateId", "autoCloseStateId"] as const)
        if (team[field] === s.id) references[field] = target.id;
      if (Object.keys(references).length) ctx.store.patch("team", team.id, { ...references, updatedAt: ctx.now });
      ctx.store.patch("workflowState", args.id, { archivedAt: ctx.now, updatedAt: ctx.now });
    },
  }),
};
